#!/usr/bin/env bash
# Regenerates Vakku-PHD/Vakku_PHDCode/Search/BridgeStateCopy.cs from the bridge's state builder, so the sidecar
# gets exactly the combat state the engine is checked against. Run again when the bridge builder changes.
set -euo pipefail
BRIDGE="${BRIDGE_SRC:?set BRIDGE_SRC to the bridge plugin folder (cli-anything-sts2/agent-harness/bridge/plugin)}"
OUT="$(dirname "$0")/../Vakku-PHD/Vakku_PHDCode/Search/BridgeStateCopy.cs"
mkdir -p "$(dirname "$OUT")"
S="$BRIDGE/BridgeMod.StateBuilder.cs"; H="$BRIDGE/BridgeMod.Helpers.cs"
{
  echo "// GENERATED by tools/vendor_state.sh from the bridge's BridgeMod.StateBuilder.cs / Helpers.cs. Do not edit."
  sed -n '1,40p' "$S" | grep '^using'
  echo "using MegaCrit.Sts2.Core.Localization;"
  echo "using System.Text;"
  echo
  echo "namespace Vakku_PHD.Vakku_PHDCode.Search;"
  echo
  echo "public static partial class BridgeStateCopy"
  echo "{"
  sed -n '15,151p' "$H"
  sed -n '218,258p' "$H"
  sed -n '443,800p' "$S"
  sed -n '1788,1827p' "$S"
  echo "}"
} | sed 's/^    private static/    internal static/' > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
